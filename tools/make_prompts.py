#!/usr/bin/env python3
"""Build the SIP phone's voice prompts into ESP32S3_SipPhone/prompts.h.

Each prompt is a WAV file in ESP32S3_SipPhone/prompts/: 16 kHz, mono, 16-bit
PCM. A missing WAV is spoken by Windows text-to-speech (System.Speech) first;
pass --tts to regenerate every WAV that way. To use your own recording,
replace the WAV in that format and run this script again, then rebuild.

    python tools/make_prompts.py          # convert, speaking missing WAVs
    python tools/make_prompts.py --tts    # re-speak every WAV first
"""
import argparse
import array
import subprocess
import sys
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKETCH = ROOT / "ESP32S3_SipPhone"
WAV_DIR = SKETCH / "prompts"
HEADER = SKETCH / "prompts.h"
RATE = 16000
MAX_SECONDS = 4

# (C name, WAV file, text spoken by text-to-speech)
PROMPTS = [
    ("wifi", "wifi_connected.wav", "Wi-Fi connected."),
    ("sip", "sip_connected.wav", "SIP phone connected successfully."),
]


def speak(text, path):
    """Write text as a 16 kHz mono 16-bit WAV with Windows text-to-speech."""
    if sys.platform != "win32":
        sys.exit(f"{path.name} is missing and text-to-speech needs Windows; supply the WAV yourself")
    ps_text = text.replace("'", "''")
    ps_path = str(path).replace("'", "''")
    script = (
        "Add-Type -AssemblyName System.Speech;"
        "$s = New-Object System.Speech.Synthesis.SpeechSynthesizer;"
        "$f = New-Object System.Speech.AudioFormat.SpeechAudioFormatInfo("
        f"{RATE}, [System.Speech.AudioFormat.AudioBitsPerSample]::Sixteen,"
        " [System.Speech.AudioFormat.AudioChannel]::Mono);"
        f"$s.SetOutputToWaveFile('{ps_path}', $f); $s.Rate = 0;"
        f"$s.Speak('{ps_text}'); $s.Dispose()"
    )
    subprocess.run(["powershell", "-NoProfile", "-NonInteractive", "-Command", script], check=True)
    print(f"spoke  {path.name}: \"{text}\"")


def load(path):
    with wave.open(str(path), "rb") as w:
        fmt = (w.getframerate(), w.getnchannels(), w.getsampwidth(), w.getcomptype())
        if fmt != (RATE, 1, 2, "NONE"):
            sys.exit(f"{path.name}: need {RATE} Hz, mono, 16-bit PCM WAV; got {fmt[0]} Hz, "
                     f"{fmt[1]} channel(s), {fmt[2] * 8}-bit, {fmt[3]}")
        samples = array.array("h", w.readframes(w.getnframes()))
    if sys.byteorder == "big":
        samples.byteswap()
    return samples


def trim(samples, threshold=300, pad_ms=30):
    """Drop leading/trailing silence, keep a short pad, fade the ends."""
    loud = [i for i, s in enumerate(samples) if abs(s) > threshold]
    if not loud:
        return samples
    pad = RATE * pad_ms // 1000
    out = samples[max(0, loud[0] - pad):min(len(samples), loud[-1] + pad)]
    fade = min(RATE // 200, len(out) // 2)  # 5 ms
    for i in range(fade):
        out[i] = out[i] * i // fade
        out[-1 - i] = out[-1 - i] * i // fade
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tts", action="store_true", help="re-speak every WAV with text-to-speech")
    args = ap.parse_args()
    WAV_DIR.mkdir(exist_ok=True)

    lines = [
        "// Generated by tools/make_prompts.py from ESP32S3_SipPhone/prompts/*.wav.",
        "// Do not edit: replace a WAV (16 kHz mono 16-bit) and run the script again.",
        "#pragma once",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "",
    ]
    for name, file, text in PROMPTS:
        path = WAV_DIR / file
        if args.tts or not path.exists():
            speak(text, path)
        samples = trim(load(path))
        if len(samples) > RATE * MAX_SECONDS:
            sys.exit(f"{file}: {len(samples) / RATE:.1f} s is longer than {MAX_SECONDS} s")
        print(f"packed {file}: {len(samples) / RATE:.2f} s, {len(samples) * 2} bytes")
        lines.append(f"// \"{text}\" ({len(samples) / RATE:.2f} s)")
        lines.append(f"static const int16_t PROMPT_{name.upper()}_PCM[{len(samples)}] = {{")
        for i in range(0, len(samples), 16):
            lines.append("  " + ",".join(str(s) for s in samples[i:i + 16]) + ",")
        lines.append("};")
        lines.append("")
    HEADER.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote  {HEADER.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
